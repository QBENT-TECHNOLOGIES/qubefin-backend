        public record ExcelReportOptions(bool ShowCompanyHeader = false, string? ReportTitle = null, string? SubHeader = null, string? GeneratedBy = null);

        #region HEADER CARD

        // The header block is a "card": it spans only the leading columns, sits
        // at the left of the sheet, and everything inside it stays centered.
        // These constants size that card from the text it has to hold.
        private const double HeaderCharWidthFactor = 0.8;   // approx px per character, per font point
        private const double HeaderCardPadding = 1.1;       // breathing room around the longest line
        private const double HeaderColumnCharWidthPx = 7.0; // ~digit width for Calibri 11 / Arial 10
        private const int MinimumCardColumns = 2;

        /// <summary>
        /// The one line shown under the sub header. Built here so the card width
        /// can be measured against the exact text that will be rendered.
        /// </summary>
        public static string BuildGeneratedInfoText(string? generatedBy)
        {
            var generatedByText = string.IsNullOrWhiteSpace(generatedBy) ? "System" : generatedBy.Trim();

            return $"Generated By: {generatedByText}    Generated On: {DateTime.Now.ToString("dd/MM/yyyy hh:mm tt", CultureInfo.InvariantCulture)}";
        }

        /// <summary>
        /// How many leading columns the header card spans: the fewest that still
        /// fit the longest header line, never below <see cref="MinimumCardColumns"/>
        /// and never past the end of the table.
        /// </summary>
        public static int ResolveHeaderCardColumnCount(ISheet sheet, int columnCount, params (string? Text, int FontPoints)[] lines)
        {
            if (columnCount <= MinimumCardColumns)
                return Math.Max(columnCount, 1);

            double requiredPx = 0;

            foreach (var (text, fontPoints) in lines)
            {
                if (string.IsNullOrWhiteSpace(text))
                    continue;

                var widthPx = text.Length * fontPoints * HeaderCharWidthFactor;

                if (widthPx > requiredPx)
                    requiredPx = widthPx;
            }

            requiredPx *= HeaderCardPadding;

            double cumulativePx = 0;

            for (var i = 0; i < columnCount; i++)
            {
                cumulativePx += (sheet.GetColumnWidth(i) / 256.0) * HeaderColumnCharWidthPx;

                if (cumulativePx >= requiredPx)
                    return Math.Max(i + 1, MinimumCardColumns);
            }

            return columnCount;
        }

        /// <summary>
        /// Card width for a standard report, measured against every header line
        /// the given options will actually render.
        /// </summary>
        public static int ResolveHeaderCardColumnCount(ISheet sheet, int columnCount, ExcelReportOptions options)
        {
            var lines = new List<(string? Text, int FontPoints)>();

            if (options.ShowCompanyHeader)
            {
                lines.Add((ExcelCompanyHeaderHelper.CompanyName, 14));
                lines.Add((ExcelCompanyHeaderHelper.CompanyAddress, 10));
                lines.Add((ExcelCompanyHeaderHelper.CompanyContact, 10));
            }

            lines.Add((options.ReportTitle, 16));
            lines.Add((options.SubHeader, 11));
            lines.Add((BuildGeneratedInfoText(options.GeneratedBy), 11));

            return ResolveHeaderCardColumnCount(sheet, columnCount, lines.ToArray());
        }

        #endregion

        public static MemoryStream CreateExcel(DataTable dataTable, ExcelReportOptions options, byte[]? logoBytes)
        {
            var workbook = new XSSFWorkbook();

            try
            {
                var sheet = workbook.CreateSheet("Report");
                ApplyColumnWidths(sheet, dataTable);

                var currentRow = 0;

                // Header card width — every header row merges across these
                // leading columns only, so the card sits at the left.
                var cardColumnCount = ResolveHeaderCardColumnCount(sheet, dataTable.Columns.Count, options);

                // Company Header
                if (options.ShowCompanyHeader)
                {
                    currentRow = ExcelCompanyHeaderHelper.AddCompanyHeader(workbook, sheet, currentRow, dataTable.Columns.Count, logoBytes, cardColumnCount);
                }

                // Report Title
                if (!string.IsNullOrWhiteSpace(options.ReportTitle))
                {
                    AddHeader(workbook, sheet, ref currentRow, options.ReportTitle, cardColumnCount);
                }

                // Report Sub Header
                if (!string.IsNullOrWhiteSpace(options.SubHeader))
                {
                    AddSubHeader(workbook, sheet, ref currentRow, options.SubHeader, cardColumnCount);
                }

                // Generated By / Generated On
                AddGeneratedInfo(workbook, sheet, ref currentRow, options.GeneratedBy, cardColumnCount);

                // Column Headers
                AddColumnHeaders(workbook, sheet, ref currentRow, dataTable);

                // Data
                if (dataTable.Rows.Count == 0)
                {
                    AddNoDataRow(workbook, sheet, ref currentRow, dataTable.Columns.Count);
                }
                else
                {
                    AddData(workbook, sheet, ref currentRow, dataTable);
                }

                var stream = new MemoryStream();

                workbook.Write(stream, leaveOpen: true);

                stream.Position = 0;

                return stream;
            }
            finally
            {
                workbook.Close();
            }
        }

        #region GENERIC (LINQ) OVERLOAD

        public static MemoryStream CreateExcel<T>(IEnumerable<T> data, ExcelReportOptions options, byte[]? logoBytes)
        {
            // Materialize ONCE — avoids re-running a deferred LINQ/EF query twice
            // (once for column widths, once for writing rows).
            var rows = data as IReadOnlyList<T> ?? data.ToList();

            var workbook = new XSSFWorkbook();

            try
            {
                var sheet = workbook.CreateSheet("Report");
                var accessors = PropertyAccessorCache<T>.Accessors;

                ApplyColumnWidths(sheet, accessors, rows);

                var currentRow = 0;

                var cardColumnCount = ResolveHeaderCardColumnCount(sheet, accessors.Length, options);

                if (options.ShowCompanyHeader)
                    currentRow = ExcelCompanyHeaderHelper.AddCompanyHeader(workbook, sheet, currentRow, accessors.Length, logoBytes, cardColumnCount);

                if (!string.IsNullOrWhiteSpace(options.ReportTitle))
                    AddHeader(workbook, sheet, ref currentRow, options.ReportTitle, cardColumnCount);

                if (!string.IsNullOrWhiteSpace(options.SubHeader))
                    AddSubHeader(workbook, sheet, ref currentRow, options.SubHeader, cardColumnCount);

                AddGeneratedInfo(workbook, sheet, ref currentRow, options.GeneratedBy, cardColumnCount);

                AddColumnHeaders(workbook, sheet, ref currentRow, accessors);

                if (rows.Count == 0)
                    AddNoDataRow(workbook, sheet, ref currentRow, accessors.Length);
                else
                    AddData(workbook, sheet, ref currentRow, accessors, rows);

                var stream = new MemoryStream();
                workbook.Write(stream, leaveOpen: true);
                stream.Position = 0;
                return stream;
            }
            finally
            {
                workbook.Close();
            }
        }

        private static void ApplyColumnWidths<T>(ISheet sheet, (string Name, Func<T, object?> Getter)[] accessors, IReadOnlyList<T> rows)
        {
            for (var i = 0; i < accessors.Length; i++)
            {
                var maxLength = ToDisplayName(accessors[i].Name).Length;

                foreach (var item in rows)
                {
                    var text = accessors[i].Getter(item)?.ToString() ?? string.Empty;
                    if (text.Length > maxLength)
                        maxLength = text.Length;
                }

                var widthChars = Math.Min(Math.Max(maxLength + 4, 10), 45);
                sheet.SetColumnWidth(i, widthChars * 256);
            }
        }

        private static void AddColumnHeaders<T>(IWorkbook workbook, ISheet sheet, ref int currentRow, (string Name, Func<T, object?> Getter)[] accessors)
        {
            var row = sheet.CreateRow(currentRow++);
            var style = CreateColumnHeaderStyle(workbook);

            for (var i = 0; i < accessors.Length; i++)
            {
                var cell = row.CreateCell(i);
                cell.SetCellValue(ToDisplayName(accessors[i].Name));
                cell.CellStyle = style;
            }
        }

        private static void AddData<T>(IWorkbook workbook, ISheet sheet, ref int currentRow, (string Name, Func<T, object?> Getter)[] accessors, IReadOnlyList<T> rows)
        {
            var dateStyle = workbook.CreateCellStyle();
            dateStyle.DataFormat = workbook.CreateDataFormat().GetFormat("dd/MM/yyyy");

            foreach (var item in rows)
            {
                var row = sheet.CreateRow(currentRow++);

                for (var i = 0; i < accessors.Length; i++)
                {
                    var cell = row.CreateCell(i);
                    var value = accessors[i].Getter(item);
                    ExcelCellHelper.SetValue(cell, value ?? DBNull.Value, dateStyle);
                }
            }
        }

        private static class PropertyAccessorCache<T>
        {
            public static readonly (string Name, Func<T, object?> Getter)[] Accessors =
                typeof(T).GetProperties(BindingFlags.Public | BindingFlags.Instance)
                    .Select(p =>
                    {
                        var instance = Expression.Parameter(typeof(T), "x");
                        var property = Expression.Property(instance, p);
                        var convert = Expression.Convert(property, typeof(object));
                        var getter = Expression.Lambda<Func<T, object?>>(convert, instance).Compile();
                        return (p.Name, Getter: getter);
                    })
                    .ToArray();
        }

        #region OBJECT (RUNTIME-TYPE) OVERLOAD — for IEnumerable<object> callers

        public static MemoryStream CreateExcel(IEnumerable<object> data, ExcelReportOptions options, byte[]? logoBytes)
        {
            var rows = data as IReadOnlyList<object> ?? data.ToList();

            // Resolve the REAL type from the first item, not from the object wrapper.
            // Falls back to object if the collection is empty (no columns to render).
            var itemType = rows.Count > 0 ? rows[0]!.GetType() : typeof(object);

            var workbook = new XSSFWorkbook();

            try
            {
                var sheet = workbook.CreateSheet("Report");
                var accessors = ObjectPropertyAccessorCache.GetAccessors(itemType);

                ApplyColumnWidths(sheet, accessors, rows);

                var currentRow = 0;

                var cardColumnCount = ResolveHeaderCardColumnCount(sheet, accessors.Length, options);

                if (options.ShowCompanyHeader)
                    currentRow = ExcelCompanyHeaderHelper.AddCompanyHeader(workbook, sheet, currentRow, accessors.Length, logoBytes, cardColumnCount);
                else
                    currentRow = ExcelCompanyHeaderHelper.AddCompanyLogo(workbook, sheet, currentRow, accessors.Length, logoBytes, cardColumnCount);

                if (!string.IsNullOrWhiteSpace(options.ReportTitle))
                    AddHeader(workbook, sheet, ref currentRow, options.ReportTitle, cardColumnCount);

                if (!string.IsNullOrWhiteSpace(options.SubHeader))
                    AddSubHeader(workbook, sheet, ref currentRow, options.SubHeader, cardColumnCount);

                AddGeneratedInfo(workbook, sheet, ref currentRow, options.GeneratedBy, cardColumnCount);

                AddColumnHeaders(workbook, sheet, ref currentRow, accessors);

                if (rows.Count == 0)
                    AddNoDataRow(workbook, sheet, ref currentRow, accessors.Length);
                else
                    AddData(workbook, sheet, ref currentRow, accessors, rows);

                var stream = new MemoryStream();
                workbook.Write(stream, leaveOpen: true);
                stream.Position = 0;
                return stream;
            }
            finally
            {
                workbook.Close();
            }
        }

        private static void ApplyColumnWidths(ISheet sheet, (string Name, Func<object, object?> Getter)[] accessors, IReadOnlyList<object> rows)
        {
            for (var i = 0; i < accessors.Length; i++)
            {
                var maxLength = ToDisplayName(accessors[i].Name).Length;

                foreach (var item in rows)
                {
                    var text = accessors[i].Getter(item)?.ToString() ?? string.Empty;
                    if (text.Length > maxLength)
                        maxLength = text.Length;
                }

                var widthChars = Math.Min(Math.Max(maxLength + 4, 10), 45);
                sheet.SetColumnWidth(i, widthChars * 256);
            }
        }

        private static void AddColumnHeaders(IWorkbook workbook, ISheet sheet, ref int currentRow, (string Name, Func<object, object?> Getter)[] accessors)
        {
            var row = sheet.CreateRow(currentRow++);
            var style = CreateColumnHeaderStyle(workbook);

            for (var i = 0; i < accessors.Length; i++)
            {
                var cell = row.CreateCell(i);
                cell.SetCellValue(ToDisplayName(accessors[i].Name));
                cell.CellStyle = style;
            }
        }

        private static void AddData(IWorkbook workbook, ISheet sheet, ref int currentRow, (string Name, Func<object, object?> Getter)[] accessors, IReadOnlyList<object> rows)
        {
            var dateStyle = workbook.CreateCellStyle();
            dateStyle.DataFormat = workbook.CreateDataFormat().GetFormat("dd/MM/yyyy");

            foreach (var item in rows)
            {
                var row = sheet.CreateRow(currentRow++);

                for (var i = 0; i < accessors.Length; i++)
                {
                    var cell = row.CreateCell(i);
                    var value = accessors[i].Getter(item);
                    ExcelCellHelper.SetValue(cell, value ?? DBNull.Value, dateStyle);
                }
            }
        }

        private static class ObjectPropertyAccessorCache
        {
            private static readonly System.Collections.Concurrent.ConcurrentDictionary<Type, (string Name, Func<object, object?> Getter)[]> _cache = new();

            public static (string Name, Func<object, object?> Getter)[] GetAccessors(Type type) =>
                _cache.GetOrAdd(type, t =>
                    t.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                        .Select(p => (p.Name, Getter: (Func<object, object?>)p.GetValue))
                        .ToArray());
        }

